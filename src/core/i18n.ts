export const i18n = {
  getMessage(key: I18nKey, substitutions?: string | string[]): string {
    if (typeof chrome !== 'undefined' && chrome.i18n) {
      return chrome.i18n.getMessage(key, substitutions);
    }
    return key;
  },

  localizeHtml(container: HTMLElement | Document = document): void {
    const elements = container.querySelectorAll<HTMLElement>('[data-i18n], [data-i18n-title], [data-i18n-placeholder], [data-i18n-aria-label]');
    elements.forEach((el) => {
      const key = el.getAttribute('data-i18n') as I18nKey | null;
      if (key) {
        const message = this.getMessage(key);
        if (message) el.textContent = message;
      }
      
      const titleKey = el.getAttribute('data-i18n-title') as I18nKey | null;
      if (titleKey) {
        const message = this.getMessage(titleKey);
        if (message) el.title = message;
      }
      
      const placeholderKey = el.getAttribute('data-i18n-placeholder') as I18nKey | null;
      if (placeholderKey && el instanceof HTMLInputElement) {
        const message = this.getMessage(placeholderKey);
        if (message) el.placeholder = message;
      }

      const ariaLabelKey = el.getAttribute('data-i18n-aria-label') as I18nKey | null;
      if (ariaLabelKey) {
        const message = this.getMessage(ariaLabelKey);
        if (message) el.setAttribute('aria-label', message);
      }
    });
  }
};
