const families = [];
function family(id, story, endings) {
  const lines = story.trim().split('\n');
  const variants = endings.trim().split('\n').map(line => {
    const split = line.indexOf('|');
    return { code: line.slice(0, split), text: line.slice(split + 1) };
  });
  if (lines.length !== 7 || variants.length !== 15) throw new Error(`Invalid family ${id}`);
  families.push({ id, lines, variants });
}

