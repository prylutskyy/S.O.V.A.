function family(name, story, endings) {
  const lines = story.trim().split('\n');
  const choices = endings.trim().split('\n').map(line => { const pos=line.indexOf('|'); return { code:line.slice(0,pos), text:line.slice(pos+1) }; });
  if (lines.length !== 7 || choices.length !== 15) throw new Error(`Invalid source: ${name}`);
  families.push({ name, lines, choices });
}

